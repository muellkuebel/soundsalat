function mix(parts: Recipe[]): Recipe {
  return { type: 'mix', parts }
}

function sound(
  category: ThemeId,
  slug: string,
  name: string,
  icon: IconName,
  duration: number,
  recipe: Recipe,
): SoundItem {
  return { id: `${category}-${slug}`, name, category, icon, duration, recipe }
}

